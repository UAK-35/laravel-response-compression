# A numbered item in a markdown list, as any of the pointer files may write one.
ORDERED_ITEM = re.compile(r"^\s*\d+[.)]\s+(.*)$")


def load_order(text: str) -> list[str]:
    """The boot sequence a file publishes as a numbered list, or nothing when it publishes none.

    A pointer exists to say where a rule is written, and the order a session loads the canonical
    files in is one of those rules: it is section 3 of `AGENTS.md`. Five pointers carried their own
    copy of it — three, four and four items long, one of them putting itself fourth and another
    listing a file the section does not — so an agent following its entry point loaded a different
    sequence than the one the canonical file states, and the copies could only drift further apart.

    The shape read is deliberately narrow. A run of numbered items whose first item names
    `AGENTS.md` is a load order; a numbered list that starts at something else is a list about
    something else, and a pointer is still allowed to keep one. Prose that mentions reading
    `AGENTS.md` first is not read at all: this refuses a list, not a sentence, because a sentence
    that says `AGENTS.md` is first is the pointer doing the one thing a pointer is for.
    """
    blocks: list[list[str]] = []
    current: list[str] = []

    for line in text.splitlines():
        item = ORDERED_ITEM.match(line)

        if item is not None:
            current.append(item.group(1).strip())
            continue

        # A blank line, or an unindented one, ends the run; an indented line is the rest of the
        # item above it - a wrapped sentence, or a path shown on its own line beneath the item.
        if current and (not line.strip() or not line.startswith((" ", "\t"))):
            blocks.append(current)
            current = []

    if current:
        blocks.append(current)

    for block in blocks:
        if len(block) >= 2 and "AGENTS.md" in block[0]:
            return block

    return []


def step_canonical(root: Path) -> list[str]:
    findings: list[str] = []
    text = read(root / "AGENTS.md")

    if not text.strip():
        return ["AGENTS.md: missing or empty - there is nothing for the other files to point at"]

    numbers = [int(number) for number, _title in SECTION.findall(text)]
    expected = list(range(0, 15))

    if numbers != expected:
        findings.append(
            f"AGENTS.md: its sections are {numbers or 'none'}, and a reader is told there are "
            f"{expected[0]}..{expected[-1]}"
        )

    titles = {title.strip().rstrip(".") for _number, title in SECTION.findall(text)}

    for pointer in POINTERS:
        path = root / pointer
        if not path.is_file():
            continue

        text_of_pointer = read(path)

        for _number, title in SECTION.findall(text_of_pointer):
            if title.strip().rstrip(".") in titles:
                findings.append(
                    f"{pointer}: restates the section `{title.strip()}` - a pointer names the "
                    "canonical file instead of repeating it"
                )

        order = load_order(text_of_pointer)
        if order:
            findings.append(
                f"{pointer}: publishes a load order of its own ({len(order)} items, the first "
                "naming `AGENTS.md`) - section 3 is the sequence, and a second copy of it goes "
                "stale the day that section gains an item"
            )

    return findings


def step_pointers(root: Path) -> list[str]:
    findings: list[str] = []

    for pointer in POINTERS:
        path = root / pointer
        if not path.is_file():
            findings.append(f"{pointer}: missing - nothing tells this tool where the rules are")
            continue
        if "AGENTS.md" not in read(path):
            findings.append(f"{pointer}: does not name AGENTS.md")

    return findings


def step_index(root: Path) -> list[str]:
    findings: list[str] = []
    index = read(root / ".agents" / "README.md")

    if not index.strip():
        return [".agents/README.md: missing or empty - it is the index of everything loadable"]

    names = [("skill", name) for name in skill_targets(root)]
    names += [
        ("agent", path.stem)
        for path in sorted((root / ".agents" / "agents").glob("*.md"))
    ]
    names += [
        ("command", path.stem)
        for path in sorted((root / ".agents" / "commands").glob("*.md"))
    ]

    for kind, name in names:
        if not whole_cell(index, name):
            findings.append(f"{kind} `{name}`: not in the index in .agents/README.md")

    # Reverse direction: a row naming something that is not there. It is read from the two index
    # tables by their first cell, so a row whose subject was renamed is a finding rather than a
    # silence - which is the half the table cannot catch by itself.
    for header in ("Authored in", "Defined in"):
        for row in table_rows(index, header):
            if not row:
                continue
            name = row[0].strip().strip("`")
            if not name:
                continue
            if name.startswith(".") or "/" in name:
                continue
            present = name in skill_targets(root)
            present = present or (root / ".agents" / "agents" / f"{name}.md").is_file()
            present = present or (root / ".agents" / "commands" / f"{name}.md").is_file()
            if not present:
                findings.append(f".agents/README.md: the row for `{name}` names nothing that exists")

    return findings


def required_skills(root: Path, kind: str) -> set[str] | None:
    """The targets `_sync.py` says want one of its pointers, or None when it cannot answer.

    Asked rather than re-derived. The generator honours `sync.gemini.enabled` and
    `sync.windsurf.enabled`, and this program required an import and a pointer for every target, so a
    skill that opted out generated cleanly and then failed verification - one flag read by one
    program and overruled by the other. An answer of None means the generator is absent or broken,
    and the caller falls back to `skill_targets`, which is the strict question, while `skills`
    reports the generator itself rather than leaving this step as the only evidence of it.
    """
    sync = root / ".skills" / "_sync.py"
    if not sync.is_file():
        return None

    result = subprocess.run(
        [sys.executable, str(sync), "--required", kind],
        cwd=root,
        capture_output=True,
        text=True,
        check=False,
    )

    if result.returncode != 0:
        return None

    return {line.strip() for line in result.stdout.splitlines() if line.strip()}


def step_skills(root: Path) -> list[str]:
    """Every generated target against what its source would write, asked of the generator itself.

    This step used to compare `_meta.json`'s `source_hash` with a hash of `instructions.md` and the
    frontmatter's `name` with the directory. Both are true of a target whose body has been edited:
    the metadata still names the source it was generated from, and the name still matches the
    directory, so an agent could read a `SKILL.md` the source no longer says while every reading
    here agreed. The comparison that catches it is the target as a whole, and the generator is the
    only thing that knows what that is - so `_sync.py --check` writes nothing, compares both files
    it owns against their expected text and names each one that differs. F02 of
    `docs/reports/0001-2026-10-30_rpt-agentic-setup-audit.md` is the same failure one program over:
    `render_local.py --check` already answered "would this be written differently" and this step was
    re-deriving a narrower version of it.

    The exit status and the error stream are read as well as the finding lines. A generator that
    crashed prints no `[FAIL]` and exits 1, and reading only the lines would report a tree with
    nothing wrong in it - a check that has gone quiet is worse than one that is loud and wrong.
    """
    sync = root / ".skills" / "_sync.py"
    if not sync.is_file():
        return [".skills/_sync.py: missing, and it is what generates every skill target"]

    result = subprocess.run(
        [sys.executable, str(sync), "--check"],
        cwd=root,
        capture_output=True,
        text=True,
        check=False,
    )

    findings = [line.strip() for line in result.stdout.splitlines() if line.strip().startswith("[FAIL]")]

    if result.returncode != 0 and not findings:
        tail = ((result.stderr or "").strip() or (result.stdout or "").strip()).splitlines()
        findings.append(
            f".skills/_sync.py --check: exited {result.returncode} without naming a target - "
            f"{tail[-1] if tail else 'no output'}"
        )

    return findings


def step_gemini(root: Path) -> list[str]:
    text = read(root / "GEMINI.md")
    if not text.strip():
        return ["GEMINI.md: missing - the tools that cannot read .agents/skills/ have no import list"]

    block = re.search(re.escape(GEMINI_BEGIN) + r"(.*?)" + re.escape(GEMINI_END), text, re.DOTALL)
    if block is None:
        return ["GEMINI.md: there is no SKILLS-IMPORT block - run python .skills/_sync.py"]

    imported = re.findall(r"@\.agents/skills/([^/]+)/SKILL\.md", block.group(1))
    present = skill_targets(root)
    required = required_skills(root, "gemini")
    wanted = present if required is None else required
    findings: list[str] = []

    for name in sorted(wanted):
        if name not in imported:
            findings.append(f"GEMINI.md: `{name}` is not imported - run python .skills/_sync.py")

    # The other direction reads the same answer, so a skill that opted out is not reported for
    # having no import and for having one at the same time.
    for name in imported:
        if name in wanted:
            continue
        if name in present:
            findings.append(
                f"GEMINI.md: imports `{name}`, which its manifest opts out of "
                "(`sync.gemini.enabled: false`) - run python .skills/_sync.py"
            )
            continue
        findings.append(f"GEMINI.md: imports `{name}`, which is not a skill - run python .skills/_sync.py")

    return findings


def step_windsurf(root: Path) -> list[str]:
    findings: list[str] = []
    rules = root / ".windsurf" / "rules"
    required = required_skills(root, "windsurf")
    wanted = set(skill_targets(root)) if required is None else required

    for name in sorted(wanted):
        if not (rules / f"{name}.windsurf.md").is_file():
            findings.append(
                f".windsurf/rules/{name}.windsurf.md: missing - a tool that cannot read "
                ".agents/skills/ has no pointer to this skill (run python .skills/_sync.py)"
            )

    # A pointer the generator wrote for a skill that is gone, or one whose `windsurf` flag was turned
    # off: written by a run, removed only by one, and `--prune` is the only thing that removes it - so
    # a rule left behind is named here rather than read as a rule somebody still wants.
    for rule in sorted(rules.glob("*.windsurf.md")):
        name = rule.name.removesuffix(".windsurf.md")
        if name in wanted or WINDSURF_MARK not in read(rule):
            continue
        findings.append(
            f".windsurf/rules/{rule.name}: generated for `{name}`, which no manifest requires - "
            "run python .skills/_sync.py --prune"
        )

    return findings


def command_forms(entry: dict) -> list[tuple[str, str]]:
    """One command's forms, each with the shell it is written for.

    Most commands are one line that either shell runs as it stands - `composer checks`, `sh
    .agents/php-bin.sh --show` - so they carry one form. The four that render an interpreter inside
    the command carry two, because the shells spell that rendering differently: bash makes the
    substitution a word with quotes around it, while PowerShell 7 needs the call operator in front
    of it to run what the substitution printed. One command, two spellings, and a reader who copies
    the wrong one gets a syntax error rather than the check.
    """
    forms = [("bash", str(entry.get("line", "")))]
    powershell = str(entry.get("powershell", "") or "")

    if powershell:
        forms.append(("PowerShell 7", powershell))

    return forms


def table_block(manifest: dict) -> str:
    commands = manifest.get("commands", {})
    tools = manifest.get("tools", {})

    lines = [
        "| Command | Runs | For |",
        "| --- | --- | --- |",
    ]
    for name, entry in commands.items():
        forms = command_forms(entry)

        # One form is written as itself, because most commands are one command; a command with two is
        # written as two and each says which shell it is for, since the whole point of the second is
        # that the first does not run there.
        runs = f"`{forms[0][1]}`" if len(forms) == 1 else " · ".join(f"{shell}: `{line}`" for shell, line in forms)
        lines.append(f"| `{name}` | {runs} | {entry['purpose']} |")

    lines += ["", "| Tool | Runs as | Version asked for | For |", "| --- | --- | --- | --- |"]
    for name, entry in tools.items():
        target = entry.get("token") or entry.get("command") or ""
        lines.append(f"| `{name}` | `{target}` | `{entry.get('pin', '')}` | {entry.get('purpose', '')} |")

    return "\n".join(lines)


def rendered_toolchain(manifest: dict) -> str:
    return (
        f"{TOOLCHAIN_BEGIN}\n"
        "<!-- rendered from .agents/toolchain.json by `python .agents/verify.py --fix`; "
        "edit the manifest, not this table -->\n\n"
        f"{table_block(manifest)}\n"
        f"{TOOLCHAIN_END}"
    )


def unreadable_program(root: Path, name: str, shell: str, line: str, script_names: set[str]) -> list[str]:
    """The program a command names, when it is not the thing that command runs.

    Read to the program rather than to the first word: `"$(python …)" bin/checks.php` renders an
    interpreter in front of a program, and the program is what has to be here. Both renderings are
    stripped for that reason, and the form is named in the finding when it is not the first one -
    a broken line in the PowerShell half is a broken command, and a reader told only that `staged`
    names nothing would look at the line that is right.
    """
    form = "" if shell == "bash" else f" (as {shell})"
    stripped = PWSH_RENDER.sub("", PHP_RENDER.sub("", line))
    renders = stripped != line
    parts = stripped.split()
    head = parts[0] if parts else ""

    if head == "composer":
        script = parts[1] if len(parts) > 1 else ""
        if script and script not in script_names:
            return [f".agents/toolchain.json: `{name}`{form} runs `{line}`, which no composer.json script provides"]
    elif head == "python":
        if len(parts) > 1 and not (root / parts[1]).is_file():
            return [f".agents/toolchain.json: `{name}`{form} names {parts[1]}, which is not here"]
    elif renders or head in ("php", "__PHP_EXE__"):
        # Both shapes name an interpreter over a program, so both are read to the program: the
        # rendered prefix is the interpreter, and the token form is the word after the token.
        program = head if renders else (parts[1] if len(parts) > 1 else "")
        if program and not (root / program).is_file():
            return [f".agents/toolchain.json: `{name}`{form} names {program}, which is not here"]

    return []


# PowerShell, asked whether each line parses, in one start: the loop reports the index of the line
# that threw and exits 1, and the caller turns that index back into the command's name. A command
# carrying quotes cannot be written into a `-Command` string without being quoted a second time, so
# the lines arrive in the environment, where they are handed over as they are.
PWSH_PARSE = (
    "$i = 0; "
    'foreach ($line in ($env:RC_COMMAND_FORMS -split "`n")) { '
    "$i++; "
    "try { [void][scriptblock]::Create($line) } "
    'catch { Write-Output "$i`: $($_.Exception.Message)"; exit 1 } }'
)


def command_shell(root: Path, name: str) -> str:
    """The shell this machine runs, asked of the machine record before PATH.

    The same order the toolchain probe asks it in, and for the same reason: `.agents/machine.local.json`
    is where this machine's PowerShell 7 is named, and PATH is what a machine without a record falls
    back to rather than what decides.
    """
    machine = root / ".agents" / "machine.local.json"
    held = ""

    if machine.is_file():
        try:
            data = json.loads(read(machine) or "{}")
        except json.JSONDecodeError:
            data = {}

        section = data.get(name, {}) if isinstance(data, dict) else {}
        held = str(section.get("exe", "")) if isinstance(section, dict) else ""

    return held or (shutil.which(name) or "")


def step_command_shells(root: Path, manifest: dict) -> list[str]:
    """Each command form, parsed by the shell it is written for.

    A form is a claim about a shell, and the two spellings of one rendering are each a syntax error
    in the other - `& (…)` is not bash, and `"$(…)" program` is not how PowerShell runs a resolved
    executable. So the question goes to the shell rather than to a pattern of this program's:
    `bash -n` reads a command and runs nothing, and PowerShell's `[scriptblock]::Create` parses a
    string and throws on a syntax error. Neither executes the command it reads, which matters -
    a check that ran them would push, release and install on every commit.

    A shell that is not here is a note rather than a finding: the hook runs on workstations, and a
    Linux runner has no PowerShell 7 on it, so the half it cannot ask is said rather than failed.
    """
    findings: list[str] = []
    forms = [
        (shell, name, line)
        for name, entry in manifest.get("commands", {}).items()
        for shell, line in command_forms(entry)
    ]

    bash = [(name, line) for shell, name, line in forms if shell == "bash"]

    if bash:
        binary = shutil.which("bash")

        if binary is None:
            NOTES.append("toolchain: no bash on this machine, so the bash forms were not parsed")
        else:
            findings += parses_as_bash(root, binary, bash)

    powershell = [(name, line) for shell, name, line in forms if shell == "PowerShell 7"]

    if powershell:
        binary = command_shell(root, "pwsh")

        if not binary:
            NOTES.append("toolchain: no PowerShell 7 on this machine, so the PowerShell forms were not parsed")
        else:
            findings += parses_as_powershell(root, binary, powershell)

    return findings


def parses_as_bash(root: Path, binary: str, forms: list[tuple[str, str]]) -> list[str]:
    """Ask bash whether the forms parse, in one read, and name the one that does not.

    One spawn for all of them because bash is started once per line otherwise and this runs in the
    pre-commit hook - thirteen starts came to three seconds on the machine this was written on, for
    a question whose answer is almost always "yes". A clean read is therefore one start; a failing
    one is read again a line at a time, because "some line in the manifest does not parse" is not a
    finding a reader can act on and the line number bash reports counts the joined lines rather than
    the commands.
    """
    answer = capture(root, binary, "-n", "-c", "\n".join(line for _name, line in forms))

    if answer.code is None:
        NOTES.append("toolchain: bash could not be started, so the bash forms were not parsed")
        return []

    if answer.code == 0:
        return []

    findings: list[str] = []

    for name, line in forms:
        single = capture(root, binary, "-n", "-c", line)
        last = (single.output.strip().splitlines() or ["no output"])[-1]

        if single.code != 0:
            findings.append(f".agents/toolchain.json: `{name}` does not parse as bash - {last}")

    return findings or [
        f".agents/toolchain.json: a bash form does not parse as it stands - {(answer.output.strip().splitlines() or ['no output'])[-1]}"
    ]


def parses_as_powershell(root: Path, binary: str, forms: list[tuple[str, str]]) -> list[str]:
    """Ask PowerShell whether each line parses, in one start, naming the one that does not.

    One process for all of them because PowerShell's own start-up is the expensive part - better
    than a third of a second each - and a hook that adds two seconds is a hook somebody turns off.
    """
    answer = capture(
        root,
        binary,
        "-NoProfile",
        "-NonInteractive",
        "-Command",
        PWSH_PARSE,
        env={"RC_COMMAND_FORMS": "\n".join(line for _name, line in forms)},
    )

    if answer.code is None:
        return []

    if answer.code == 0:
        return []

    # The parser names the line it stopped on, so the command is named rather than the index.
    reported = re.match(r"^(\d+)\s*:", answer.output.strip())

    if reported:
        index = int(reported.group(1)) - 1

        if 0 <= index < len(forms):
            return [f".agents/toolchain.json: `{forms[index][0]}` does not parse as PowerShell 7 - {answer.output.strip()}"]

    return [f".agents/toolchain.json: a PowerShell form does not parse - {answer.output.strip()}"]


def step_toolchain(root: Path) -> list[str]:
    findings: list[str] = []
    manifest = json.loads(read(root / ".agents" / "toolchain.json") or "{}")

    if not manifest.get("commands"):
        return [".agents/toolchain.json: no commands - there is nothing to render or check"]

    composer = json.loads(read(root / "composer.json") or "{}")
    requirement = composer.get("require", {}).get("php")
    pin = manifest.get("tools", {}).get("php", {}).get("pin")

    if requirement and pin and requirement != pin:
        findings.append(
            f".agents/toolchain.json: the php pin is `{pin}` and composer.json requires `{requirement}` "
            "- one decision written twice, and the two disagree"
        )

    scripts = composer.get("scripts", {})
    script_names = set(scripts) if isinstance(scripts, dict) else set()

    # Every form of every command, each read to the program it runs: the two spellings of one
    # rendering are one command, and a check that understood only the bash one would pass a
    # PowerShell line naming a file nobody has.
    for name, entry in manifest.get("commands", {}).items():
        for shell, line in command_forms(entry):
            findings += unreadable_program(root, name, shell, line, script_names)

    findings += step_command_shells(root, manifest)

    canonical = read(root / "AGENTS.md")
    block = re.search(re.escape(TOOLCHAIN_BEGIN) + r".*?" + re.escape(TOOLCHAIN_END), canonical, re.DOTALL)
    expected = rendered_toolchain(manifest)

    if block is None:
        findings.append("AGENTS.md: no TOOLCHAIN block - run python .agents/verify.py --fix")
    elif block.group(0).strip() != expected.strip():
        findings.append(
            "AGENTS.md: the command table is not what .agents/toolchain.json says "
            "- run python .agents/verify.py --fix"
        )

    for path in [root / pointer for pointer in POINTERS] + [root / "AGENTS.md", root / ".agents" / "README.md"]:
        if path.is_file() and VENDOR_SHIM.search(read(path)):
            findings.append(
                f"{rel(path, root)}: names a vendor/bin shim - a shim runs whichever php is on PATH, "
                "and bin/tool.php is how a tool is run here"
            )

    # And the same refusal one word further in: a shim is a second interpreter, and an interpreter
    # written in front of a command is that shim left out. Which names and which programs count is the
    # platform's answer rather than this function's, because an interpreter is spelled per system.
    findings += interpreter_restated(root)

    return findings


def interpreter_rule() -> dict[str, object]:
    """This platform's rule: the names it spells an interpreter with, and the programs it runs.

    Three entries and one answer, chosen by the machine rather than by the caller: a rule that took a
    platform argument would be a rule every caller could ask about a platform it is not running on,
    and the question here is what *this* machine's commands may say.
    """
    if os.name == "nt":
        return INTERPRETER_RULES["windows"]

    return INTERPRETER_RULES["darwin" if sys.platform == "darwin" else "linux"]


def layer_files(root: Path) -> list[Path]:
    """Every file in the layer, which is where a command is handed over rather than described.

    The prose records are not in it: `docs/`, the README and the changelog explain a command instead
    of handing one over, and a command inside a sentence is a sentence - the distinction
    `IndexNumbers::phrase` makes when it leaves the changelog and the tests alone. What is here is the
    rules, the pointers, the agentic files, the programs in `bin/`, the hook and the workflow.
    """
    files: list[Path] = []

    for entry in LAYER:
        path = root / entry

        if path.is_dir():
            files += [candidate for candidate in sorted(path.rglob("*")) if candidate.is_file()]
        elif path.is_file():
            files.append(path)

    return files


# What a walk over the repository leaves out, for the case where there is no git to ask: the
# version-control internals, the two dependency trees and the byte-code caches a tool leaves beside
# its source. None of them is this repository's content, and a tree that is not a checkout is the
# selftest's own planted copy rather than something a reader was handed.
WALK_PAST = {".git", "vendor", "node_modules", "__pycache__"}


def repository_files(root: Path) -> list[Path]:
    """Every file this repository carries, wherever it is - which is what "anywhere" has to mean.

    The layer is where a command is handed over rather than described, and it was the right set for as
    long as this question was only asked of the agentic files. It is the wrong set for the question
    itself: a restated interpreter in a runbook, in the README or in a test is the same failure as one
    in `AGENTS.md`, and reading only the layer left every one of those unread - so a later change could
    put back by hand what the layer had already been made to satisfy, and nothing would say so.

    Asked of git where there is a repository to ask, because the answer wanted is the files a commit
    would carry rather than everything on the disk: one `ls-files` gives the tracked files and the
    untracked ones no ignore rule covers, in one process, and it is the same listing the PHP guards
    read. A tree that is not a checkout - the selftest's planted copy - has no git to ask, so it is
    walked instead, past the three directories in `WALK_PAST`.
    """
    if is_a_repo(root):
        result = subprocess.run(
            ["git", "-C", str(root), "ls-files", "--cached", "--others", "--exclude-standard"],
            capture_output=True,
            text=True,
            check=False,
        )

        if result.returncode == 0:
            return [root / name for name in result.stdout.splitlines() if name and (root / name).is_file()]

    files: list[Path] = []

    for path in sorted(root.rglob("*")):
        if not path.is_file() or any(part in WALK_PAST for part in path.relative_to(root).parts):
            continue

        files.append(path)

    return files


def interpreter_restated(root: Path) -> list[str]:
    """Every line of the repository that writes an interpreter in front of a command, on this platform.

    Read line by line rather than by file, because that is what the failure is: a command a reader
    copies with the answer to "which PHP" already written into it. The interpreter is one of the
    platform's names and the program is the word after it, which is what lets the one exception be a
    program - `bin/bootstrap.php` - rather than a whole line.

    Read over the whole repository rather than over the layer, because the failure is about the answer
    to "which PHP" rather than about which file gives it: a runbook, a README or a program that
    restates an interpreter is the same failure as `AGENTS.md` doing it. The one file that may write
    the interpreter itself is `.agents/machine.local.json`, which is where this machine's PHP is
    named; the file this rule is written in is excused beside it, because the rule has to quote the
    shape it refuses.

    Each finding names the platform it was found on, because that is the axis the rule is decided on:
    a line this refuses on Windows is a line a Linux reader would not write this way at all, and a
    reader who does not know which rule they met cannot tell whether the rule or the command is wrong.
    """
    rule = interpreter_rule()
    os_name = str(rule["os"])
    # The interpreter has to be a word of its own. `@` is Composer's word for the interpreter it is
    # already under, and a dot is what keeps the tail of a filename out of the reading: `Foo.php` is a
    # path, not the word `php`, and a listing with two paths a tab apart - `files.tsv`, a table in
    # `docs/` - would otherwise read as one of them running the other. A path that really names the
    # interpreter is still read, because `/` and a space are neither.
    pattern = re.compile(
        r"(?<!@)(?<![A-Za-z0-9_.-])(?P<interpreter>"
        + "|".join(re.escape(str(name)) for name in rule["names"])
        + r")[ \t]+(?P<program>[A-Za-z0-9_./\\-]+(?:"
        + "|".join(re.escape(str(suffix)) for suffix in rule["programs"])
        + r"))"
    )
    findings: list[str] = []

    for path in repository_files(root):
        where = rel(path, root)

        if where in INTERPRETER_FILES or where == MACHINE_NAME:
            continue

        # A file that is not text is not a command: `.agents/` holds byte-code caches beside the
        # checks that wrote them, and a decode error would be this reading failing on a file it was
        # never about.
        try:
            contents = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue

        for number, line in enumerate(contents.splitlines(), 1):
            found = pattern.search(line)

            if found is None:
                continue

            program = found.group("program").replace("\\", "/").removeprefix("./").lstrip("/")

            if program in INTERPRETER_PROGRAMS:
                continue

            findings.append(
                f"{where}:{number}: restates an interpreter in front of a command on {os_name} "
                f"(`{found.group('interpreter')} {found.group('program')}`) - that runs under whichever "
                "`php` is first on PATH, and bin/tool.php runs a tool under the interpreter that is "
                "already running, while `.agents/php-bin.sh` is what says which one that is"
            )

    return findings


def step_interpreter(root: Path) -> list[str]:
    """One file decides which PHP this checkout runs, and nothing else decides again.

    Four things used to answer that question separately: the pre-commit hook climbed a ladder of its
    own, the workflow installed a version written into it, `bin/tool.php` ran whatever started it,
    and `bin/coverage.php` measured its floors under whatever Composer runs. The ladder is
    `.agents/php-bin.sh`'s now, and so is the requirement `--matrix` turns into a build, which
    leaves this step to read the three callers that can carry a second copy:

      * the hook has to ask the resolver, and may not carry a rung of the ladder - the failure this
        exists for is that block being written back one day because it is only four lines;
      * a workflow may not state the version, in a matrix or anywhere else, because a build that
        installs its own idea of the requirement is the two-answers problem one layer out;
      * no PHP file but `Tests\\Support\\PhpBinary` may resolve an interpreter for itself.

    What it does not do: it reads the resolver rather than running it (`tools` asks it to prove its
    own ladder, and `--pin` in `.agents/toolchain.json` is checked against `composer.json` by the
    step above), and it judges only what a file says - a resolution assembled at runtime out of
    pieces is beyond a reading, and beyond what a second copy looks like in practice.
    """
    findings: list[str] = []
    resolver = root / ".agents" / "php-bin.sh"

    if not resolver.is_file():
        return [
            ".agents/php-bin.sh is not here, and it is the one place this checkout decides which PHP "
            "runs - the hook, the workflow and the coverage runner are all written to ask it"
        ]

    hook = root / ".githooks" / "pre-commit"
    if hook.is_file():
        text = read(hook)

        if "php-bin.sh" not in text:
            findings.append(
                ".githooks/pre-commit: does not ask .agents/php-bin.sh for the interpreter, so the hook "
                "is deciding it again - that ladder lives in one file, and this is written to ask it"
            )

        for number, line in enumerate(text.splitlines(), 1):
            if LADDER.search(line):
                findings.append(
                    f".githooks/pre-commit:{number}: carries a rung of the ladder (`{line.strip()}`) - "
                    "a second copy of the resolution is the failure .agents/php-bin.sh exists to stop"
                )

    requirement = str(json.loads(read(root / "composer.json") or "{}").get("require", {}).get("php", ""))

    # The constraint as written, and the version it names: `^8.4` and `8.4` are the same decision
    # written two ways, and a workflow that carries either has a second copy of it.
    versions = [needle for needle in (requirement, requirement.lstrip("^~>= ")) if needle]

    for workflow in sorted(root.glob(".github/workflows/*.yml")):
        where = rel(workflow, root)
        text = read(workflow)

        if "php-bin.sh" not in text:
            findings.append(
                f"{where}: does not ask .agents/php-bin.sh --matrix which PHP to install, so the "
                "version it builds is written down here as well as in composer.json"
            )

        for number, line in enumerate(text.splitlines(), 1):
            code = line.split("#", 1)[0].strip()

            if code and PHP_VERSION.search(line):
                findings.append(
                    f"{where}:{number}: states the PHP version (`{code}`) - `require.php` is where it is "
                    "written, and `sh .agents/php-bin.sh --matrix` is how the job reads it"
                )

                continue

            for version in versions:
                if version and version in line:
                    findings.append(
                        f"{where}:{number}: states `{version}`, the version composer.json requires - "
                        "the matrix is read from it, and a version written into a workflow is a second copy"
                    )

                    break

    for path in sorted([*((root / "bin").glob("*.php")), *((root / "tests").rglob("*.php"))]):
        where = rel(path, root)

        if where == "tests/Support/PhpBinary.php":
            continue

        for number, line in enumerate(read(path).splitlines(), 1):
            if ("php-bin.sh" in line or "machine.local.json" in line) and CONSUMES.search(line):
                findings.append(
                    f"{where}:{number}: resolves an interpreter for itself (`{line.strip()}`) - "
                    "the answer is `.agents/php-bin.sh`'s, and Tests\\Support\\PhpBinary is the one PHP "
                    "reader of it"
                )

    # And the program running this step, which used to be a fifth decider: it read the machine record
    # and fell through to PATH, so `RESPONSE_COMPRESSION_PHP` reached the hook, `bin/tool.php` and
    # `bin/coverage.php` and not the verifier that runs them - and a check run under an interpreter
    # nothing else agreed to is the failure that leaves no trace. The reading is behavioural rather
    # than a pattern over this file, because what a second copy looks like here is a function body
    # rather than a line: an override is planted for the length of one call and the answer has to be
    # that override. `override-ignored` in the selftest proves the reading fires by taking the
    # resolver's first rung away.
    if shutil.which("sh") is None:
        NOTES.append(
            "interpreter: no `sh` on PATH, so .agents/verify.py's own resolution was not asked - "
            "the resolver cannot be run without one"
        )
    else:
        planted = "an-override-planted-by-the-interpreter-step"
        held = os.environ.get(PHP_OVERRIDE)
        os.environ[PHP_OVERRIDE] = planted

        try:
            resolved, rung = php_resolution(root)
        finally:
            if held is None:
                os.environ.pop(PHP_OVERRIDE, None)
            else:
                os.environ[PHP_OVERRIDE] = held

        if resolved != planted or rung != ENVIRONMENT_RUNG:
            findings.append(
                f".agents/verify.py: resolves the interpreter itself - with {PHP_OVERRIDE} set it "
                f"answered `{resolved or 'nothing'}` from `{rung or 'no rung'}`, and the hook, "
                "bin/tool.php and bin/coverage.php all run what `.agents/php-bin.sh` resolves"
            )

    return findings


def step_interpreter_token(root: Path) -> list[str]:
    """No token is left where the interpreter goes.

    The `interpreter` step and the `toolchain` rule beside it refuse an interpreter written as a name
    in front of a command, because a name runs whatever that name is first on `PATH`. This is the
    other half of the same line: the token that stands for this machine's PHP, left bare in front of
    the program instead of being rendered into the command. It is not a second copy of an answer -
    it is the absence of one, and it fails differently: nothing substitutes the placeholder, so what
    a reader copies is a line the shell hands to a program called `__PHP_EXE__`.

    The rule is platform-free on purpose. A name is spelled per system, which is why the rule above is
    decided by the machine it runs on; a token is the same nine characters everywhere, and the rendering
    that replaces it is the same command everywhere too - so this fires on all three platforms rather
    than only on the one this package is developed on.

    What it leaves alone is the token being *shown*: quoted by a backtick or a quote, because that is a
    reader being told what the token is, and a sentence that mentions it, because `__PHP_EXE__ is this
    machine's PHP` has no program after it. The file this rule is written in is excused the same way the
    `interpreter` rule excuses it - the rule quotes the failure it refuses.
    """
    findings: list[str] = []

    for path in layer_files(root):
        where = rel(path, root)

        if where in INTERPRETER_FILES or where == MACHINE_NAME:
            continue

        # A file that is not text is not a command, the same way the `interpreter` rule reads it: a
        # decode error would be this reading failing on a file it was never about.
        try:
            contents = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue

        for number, line in enumerate(contents.splitlines(), 1):
            found = BARE_TOKEN.search(line)

            if found is None:
                continue

            token = found.group("token")
            program = found.group("program")

            findings.append(
                f"{where}:{number}: leaves `{token}` standing where an interpreter goes "
                f"(`{token} {program}`) - the token is a placeholder a reader has to substitute before "
                "anything runs, so the command renders it in the line itself: "
                f'"$(python .agents/render_local.py --value {token})" {program}'
            )

    return findings


def step_tokens(root: Path) -> list[str]:
    findings: list[str] = []
    known = KNOWN_TOKENS

    candidates = [root / pointer for pointer in POINTERS]
    candidates += [root / "AGENTS.md"]
    candidates += [
        path
        for base in (".agents", ".skills")
        for path in sorted((root / base).rglob("*"))
        if path.is_file() and path.suffix in (".md", ".json", ".py")
    ]

    for path in candidates:
        if not path.is_file():
            continue

        where = rel(path, root)
        excused = GENERIC_TOKENS | FIXTURE_TOKENS.get(where, set())

        for token in sorted(set(TOKEN.findall(read(path))) - known - excused):
            findings.append(
                f"{where}: `{token}` is not one of {', '.join(sorted(known))} - "
                "a token nothing knows is a name nothing resolves"
            )

    # The one file that names this machine is the one file that must not be committed. The question
    # is asked of git's own ignore rules rather than of a copy of them kept here.
    if is_a_repo(root) and not ignored(root, ".agents/machine.local.json"):
        findings.append(
            ".agents/machine.local.json: not ignored - it holds this machine's paths, and a commit "
            "would carry them"
        )

    # Every settings template has to parse, and the rendered file has to be what its template would
    # produce. The rendering is not repeated here: `render_local.py` owns it, and it answers --check
    # for exactly this question. That program also says how much of its own record the machine file
    # has written, and the filter below is where the two kinds are told apart: a `[FAIL]` line is a
    # finding, and a note is something the reader of `--check` is shown on a machine that is not
    # wrong - a fresh `--init` opens every section it cannot fill, so failing here would fail the
    # clone `bin/bootstrap.php` has just set up.
    for template in sorted(root.glob(".*/**/*.example")):
        if not template.is_file():
            continue

        where = rel(template, root)
        source = read(template)

        try:
            json.loads(source)
        except json.JSONDecodeError:
            findings.append(f"{where}: not readable as JSON")

        # And the placeholders it names, which is the second thing a template can get wrong on its
        # own: a committed template is read on every machine, so `__PHP_PATH__` where the table says
        # `__PHP_EXE__` was rendered as itself on all of them. Asked here as well as by the renderer,
        # because this half runs on a tree with no machine file - which is where a wrong template
        # would otherwise be read only by the machine that happened to have a record.
        excused = GENERIC_TOKENS | FIXTURE_TOKENS.get(where, set())

        for token in sorted(set(TOKEN.findall(source)) - known - excused):
            findings.append(
                f"{where}: names {token}, which nothing resolves - the tokens are "
                f"{', '.join(sorted(known))}"
            )

    # The comparison needs no repository, and gating it on one is how it stopped checking: it reads a
    # template and the file rendered from it and asks git nothing. Every tree that is not a checkout -
    # the archive a consumer unpacks, a copy of the package beside a site, this program's own planted
    # fixture - used to have the whole question skipped and report nothing about it. What is left that
    # genuinely needs a repository is the ignore rule above, which asks git.
    renderer = root / ".agents" / "render_local.py"
    if renderer.is_file():
        answer = capture(root, sys.executable, str(renderer), "--check")
        before = len(findings)
        machine = (root / ".agents" / "machine.local.json").is_file()

        # One pass over the lines, each read for the prefix that says which kind it is: a
        # `[FAIL]` is a finding, and a `[NOTE]` is carried into this run's report. Every note,
        # not only the summary: the summary says which state the record is in, and the lines
        # under it name the sections still empty and what each one is for - which is the half a
        # session needs to finish the file, and the half it would otherwise have to know to ask
        # `--check` for. None of it fails the run: a fresh `--init` opens every section it
        # cannot fill, so `bin/bootstrap.php` would go red on the file its own first step wrote.
        #
        # A clone with no machine record is the state `--init` has not been run in, and the
        # renderer says so by naming the values it has none of. Those lines are that state rather
        # than a fault, so on such a tree they are not findings - but every other `[FAIL]` is,
        # because a template that does not parse is wrong on every machine.
        for line in answer.output.splitlines():
            stripped = line.strip()

            if stripped.startswith("[FAIL]"):
                if machine or "no value for" not in stripped:
                    findings.append(stripped)
            elif stripped.startswith("[NOTE]"):
                NOTES.append(stripped)

        # The status is judged as well, and judged separately from the lines it printed: reading
        # only the prefixes made a renderer that raised before printing anything - a syntax
        # error, an import that is not there - identical to a renderer with nothing to report.
        # A non-zero status that already produced a finding is not counted twice; one that
        # produced none is exactly the crash this reading exists for. Without a record, status 1
        # is the missing-values answer above and anything else is a crash.
        last = (answer.output.strip().splitlines() or [""])[-1]

        if answer.code is None:
            findings.append(".agents/render_local.py --check: could not be run")
        elif answer.code != 0 and len(findings) == before and (machine or answer.code != 1):
            findings.append(
                f".agents/render_local.py --check: exited {answer.code} without naming a file - "
                f"{last or 'no output'}"
            )

        if not machine:
            NOTES.append(
                "tokens: no .agents/machine.local.json here, so the rendered settings were not judged "
                "- run python .agents/render_local.py --init"
            )

    return findings


def is_a_repo(root: Path) -> bool:
    """Is *this* directory the top of a checkout, rather than one sitting inside another one.

    The readings ask whether the tree they were handed is a repository they may put a question to,
    and `rev-parse --git-dir` answered a different one: it succeeds in any directory under a work
    tree. That was harmless for as long as every tree without a repository of its own lived outside
    this checkout - and the selftest's planted copies live inside it now, under `build/`. Asked the
    old way, a planted copy reported as a repository, `git ls-files` answered with the files under
    it that *this* repository tracks - none, because `build/` is ignored - and every reading built
    on that listing read nothing on a tree that is supposed to be full of the layer.

    A tree that is not a checkout is not a defect, which is why this is a predicate rather than a
    finding: `repository_files` walks it instead, past the directories a walk leaves alone. And the
    question is asked as itself rather than by comparing paths: `--show-prefix` prints how far this
    directory is from the top of its work tree, so empty is the top of it, and no shell's spelling
    of a path has to agree with git's.
    """
    try:
        result = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "--show-prefix"],
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError:
        return False

    return result.returncode == 0 and result.stdout.strip() == ""


def ignored(root: Path, path: str) -> bool:
    result = subprocess.run(
        ["git", "-C", str(root), "check-ignore", "-q", path],
        capture_output=True,
        text=True,
        check=False,
    )

    return result.returncode == 0


def step_descriptions(root: Path) -> list[str]:
    findings: list[str] = []

    for source in skill_sources(root):
        manifest = read(root / ".skills" / source / "skill.yaml")
        instructions = read(root / ".skills" / source / "instructions.md")

        description = ""
        for line in manifest.splitlines():
            if line.startswith("description:"):
                description = line.partition(":")[2].strip().strip('"')
                break

        if not description:
            findings.append(f".skills/{source}/skill.yaml: no description")
            continue

        defined = {match.split()[0] for match in INSTRUCTION_COMMAND.findall(instructions)}

        if not defined:
            findings.append(
                f".skills/{source}/instructions.md: defines no commands, so the description can only "
                "name things the skill does not do"
            )
            continue

        for command in command_names(description):
            if command not in defined:
                findings.append(
                    f".skills/{source}: the description names `{command}`, and its instructions.md "
                    "defines no command by that name"
                )

    return findings


class Answer(NamedTuple):
    """What a probe came back with: the status it exited with, and what it printed.

    `code is None` is the one case that is not an answer - the program could not be started at all,
    which `subprocess` reports as an exception rather than as a status. Every other shape, including
    a non-zero status with a version line on it, is something a caller has to read for itself.
    """

    code: int | None
    output: str


def capture(root: Path, *command: str, timeout: int = 300, env: dict[str, str] | None = None) -> Answer:
    """A command's status beside its output, rather than only its output.

    A probe is asking a tool a question, so a non-zero exit is an answer too - it is the caller that
    decides whether the answer is bad news, which is why this does not raise. What the caller cannot
    decide without it is *whether it ran at all*, and that is the status: dropping it here is how a
    tool that printed a usage line and crashed came to be recorded as having answered, which is F11
    of `docs/reports/0001-2026-10-30_rpt-agentic-setup-audit.md`. stdout and stderr are merged,
    because the question is what the program said and the line that explains a failure is as often
    on the second stream as on the first.
    """
    # The environment is this one with the given lines added, rather than a replacement: a probe runs
    # the programs this machine has, on the PATH it has, and only a value the caller is handing to the
    # program it starts is new. Handing a whole environment over would be a second answer to what this
    # machine is, which is the thing `.agents/machine.local.json` exists to hold.
    environment = None if env is None else {**os.environ, **env}

    try:
        result = subprocess.run(
            list(command),
            cwd=root,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
            env=environment,
        )
    except (OSError, subprocess.TimeoutExpired):
        return Answer(code=None, output="")

    return Answer(code=result.returncode, output=ANSI.sub("", (result.stdout or "") + (result.stderr or "")))


def satisfies(version: str, pin: str) -> bool:
    """Whether a version answers a pin written as `^X.Y`, `X.Y` or a bare major."""
    if not pin:
        return True

    found = [int(part) for part in re.findall(r"\d+", version)[:3]]
    wanted = [int(part) for part in re.findall(r"\d+", pin)]

    if not found or not wanted:
        return False

    if pin.startswith("^"):
        return found[0] == wanted[0] and found[: len(wanted)] >= wanted

    return found[: len(wanted)] >= wanted


def manifest_tools(root: Path) -> dict[str, dict[str, str]]:
    """The tool manifest the package runs its tools from: `bin/tool-paths.php`, asked as data.

    An entry there is a record rather than a path - the file that runs a tool, the version the
    package pins it at, and what it is for - so the manifest is *asked* rather than parsed: PHP is
    run on a line that requires it and prints it as JSON, which is the same thing `bin/tool.php`
    does with it a line later, where a pattern over the source would be a reading of the syntax
    those records happen to be written in. `tests/Unit/Support/ToolPathsTest.php` owns the rules
    about what may be in it, and a second copy of the map here would be the very thing that guard
    refuses - which is also why the pins are not compared here: that comparison is the guard's own
    reading (`ToolPaths::drift`), reached by the `gate` step.
    """
    php = php_binary(root)
    manifest = root / "bin" / "tool-paths.php"

    if php is None or not manifest.is_file():
        return {}

    # Named as PHP's own source rather than as a path this program opens: single quotes, so a `$` in
    # a directory name is a character rather than the start of a variable.
    target = str(manifest).replace("\\", "/").replace("'", "\\\\'")
    answer = capture(root, php, "-r", f"echo json_encode(require '{target}');")

    if answer.code != 0:
        return {}

    try:
        data = json.JSONDecoder().raw_decode(answer.output.lstrip())[0]
    except json.JSONDecodeError:
        return {}

    if not isinstance(data, dict):
        return {}

    return {
        str(name): {
            "path": entry["path"],
            "pin": str(entry.get("pin", "")),
            "why": str(entry.get("why", "")),
        }
        for name, entry in data.items()
        if isinstance(entry, dict) and isinstance(entry.get("path"), str) and entry["path"] != ""
    }


# The health table the toolchain probe fills in as it asks each question: the version a tool
# reported, the pin it was held to, and whether it answered at all. It is printed once at the end of
# a run as a single table, so a red run says which part of the machine moved without the reader
# having to match a finding's wording back to the tool it is about.
HEALTH: list[dict[str, str]] = []


def health(tool: str, found: str, pin: str, ran: bool) -> None:
    """Record one row: the version a tool reported, the pin it was held to, and whether it ran."""
    HEALTH.append(
        {
            "tool": tool,
            "found": " ".join(found.split()) or "-",
            "pin": pin or "-",
            "ran": "yes" if ran else "no",
        }
    )


def health_table() -> str:
    """The rows the toolchain probe collected, aligned as one table - or nothing if it never ran."""
    if not HEALTH:
        return ""

    headers = ("tool", "found", "pin", "ran")
    rows = [[row[header] for header in headers] for row in HEALTH]
    widths = [max(len(headers[index]), *(len(row[index]) for row in rows)) for index in range(len(headers))]

    lines = ["  ".join(headers[index].ljust(widths[index]) for index in range(len(headers))).rstrip()]
    lines += [
        "  ".join(row[index].ljust(widths[index]) for index in range(len(headers))).rstrip() for row in rows
    ]

    return "\n\nhealth\n" + "\n".join(f"  {line}" for line in lines)


def step_tools(root: Path) -> list[str]:
    """Every tool and every process this package needs, asked to work rather than assumed to.

    The layer steps above read files; this one runs programs. Each thing it asks is a question the
    package's own commands depend on the answer to: which PHP is being used and does it carry the
    extensions `composer.json` requires, is there a coverage driver for the floor, does the tool
    manifest still resolve to the tools it records, is the hook this repository documents actually
    enabled in this clone, and is there a `vendor/` at all.

    A missing tool is a finding here, not a skip: the gate can skip a check on a machine that lacks
    the tool, but "the processes this package needs do not run here" is the answer to the question
    this step was asked.
    """
    findings: list[str] = []
    manifest = json.loads(read(root / ".agents" / "toolchain.json") or "{}")
    tools = manifest.get("tools", {})
    composer = json.loads(read(root / "composer.json") or "{}")

    # 1. PHP, its version against the pin, the extensions it must carry, and a coverage driver.
    machine = root / ".agents" / "machine.local.json"
    declared = ""

    if machine.is_file():
        try:
            declared = str((json.loads(read(machine)).get("php", {}) or {}).get("exe", ""))
        except json.JSONDecodeError:
            declared = ""

    # A machine file that names an interpreter which is not there is answered by falling back to
    # PATH, and a silent fallback is how a machine ends up running the gate under a second PHP.
    if declared and not Path(declared).is_file():
        NOTES.append(
            f"tools: .agents/machine.local.json names {declared} as this machine's PHP, and there is "
            "nothing there - the probes below fell back to whatever `php` is on PATH"
        )

    php = php_binary(root)
    loaded: set[str] = set()

    if php is None:
        findings.append(
            "php: no interpreter found - neither .agents/machine.local.json nor PATH names one, and "
            "every command this package runs needs it (python .agents/render_local.py --init)"
        )
    else:
        answer = capture(root, php, "-r", "echo PHP_VERSION;")
        pin = str(tools.get("php", {}).get("pin", ""))
        version = (answer.output.strip().splitlines() or [""])[0]
        health("php", version, pin, answer.code == 0)

        if answer.code is None:
            findings.append(f"php: {php} could not be run")
        elif answer.code != 0:
            findings.append(f"php: {php} exited {answer.code} when asked its version - {version or 'no output'}")
        elif not satisfies(version, pin):
            findings.append(
                f"php: {php} reports {version}, and .agents/toolchain.json pins `{pin}` - the "
                "gate and the floor were not measured under the interpreter they were written for"
            )

        modules = capture(root, php, "-m")
        loaded = {line.strip().lower() for line in modules.output.splitlines()}

        for requirement in sorted(name for name in composer.get("require", {}) if name.startswith("ext-")):
            extension = requirement[4:].lower()
            if extension not in loaded:
                findings.append(
                    f"php: `{requirement}` is required by composer.json and not loaded by {php} - the "
                    "package cannot run here, whatever the gate says about the other checks"
                )

        loadable = capture(root, php, "-r", "echo implode(',', array_filter(['pcov','xdebug'], 'extension_loaded'));")
        if not loadable.output.strip():
            findings.append(
                "php: neither PCOV nor Xdebug is loaded, so composer test:unit cannot measure the "
                "floor - it reports that rather than a number, which is the honest answer to this"
            )

    # 2. Composer, and the PHP it runs under. The version is probed, because a library gitignores its
    #    lock and the manifest is the only committed statement of anything.
    phar = root / "composer.phar"
    composer_command: list[str] = [php, str(phar)] if php and phar.is_file() else ["composer"]
    composer_answer = capture(root, *composer_command, "--version")
    composer_pin = str(tools.get("composer", {}).get("pin", ""))
    composer_found = ""
    composer_first = (composer_answer.output.strip().splitlines() or [""])[0]

    if composer_answer.code is None:
        findings.append("composer: not runnable - neither composer.phar beside this checkout nor composer on PATH")
    elif composer_answer.code != 0:
        # A tool that starts and fails is not a tool that ran. The version it printed on its way out
        # is the shape this used to read as success, because non-empty output was the whole of it.
        findings.append(
            f"composer: `{' '.join(composer_command)} --version` exited {composer_answer.code} - "
            f"{composer_first or 'no output'}"
        )
    else:
        match = re.search(r"Composer version\s+(\S+)", composer_answer.output)
        if match is not None:
            composer_found = match.group(1)
        if match is None:
            findings.append(f"composer: could not read a version out of `{' '.join(composer_command)} --version`")
        elif not satisfies(match.group(1), composer_pin):
            findings.append(
                f"composer: {match.group(1)} does not answer the pin `{composer_pin}` - every script in "
                "composer.json is a Composer 2 script, and this is what runs them"
            )

    health("composer", composer_found, composer_pin, composer_answer.code == 0)

    # 3. Python, which is running this program, and PowerShell 7, which the Windows snippets assume.
    health("python", sys.version.split()[0], "3.9", True)

    if sys.version_info < (3, 9):
        findings.append(f"python: {sys.version.split()[0]} is older than the 3.9 these programs need")

    if os.name == "nt":
        pwsh = str((json.loads(read(machine) or "{}").get("pwsh", {}) or {}).get("exe", "")) if machine.is_file() else ""
        pwsh = pwsh or (shutil.which("pwsh") or "")
        pwsh_answer = (
            capture(root, pwsh, "-NoProfile", "-Command", "$PSVersionTable.PSVersion.ToString()")
            if pwsh
            else Answer(code=None, output="")
        )
        pin = str(tools.get("pwsh", {}).get("pin", ""))
        version = (pwsh_answer.output.strip().splitlines() or [""])[0]
        health("pwsh", version, pin, pwsh_answer.code == 0)

        if pwsh_answer.code is None:
            findings.append(
                "pwsh: PowerShell 7 was not found - the Windows snippets in AGENTS.md and the skills "
                "are written for it (python .agents/render_local.py --init)"
            )
        elif pwsh_answer.code != 0:
            findings.append(f"pwsh: exited {pwsh_answer.code} when asked its version - {version or 'no output'}")
        elif not satisfies(version, pin):
            findings.append(f"pwsh: reports {version}, and the pin is `{pin}`")
    else:
        NOTES.append("tools: not Windows, so the PowerShell probe was left out")

    # 4. Git, and the hook this repository documents. The hook is a clone-local setting, so a clone
    #    that has not enabled it is a note rather than a finding - but it is worth saying out loud,
    #    because the gate is what a contributor is told runs before a commit.
    git = shutil.which("git")
    git_answer = capture(root, "git", "--version") if git else Answer(code=None, output="")
    git_version = (git_answer.output.strip().splitlines() or [""])[0]
    health("git", git_version.removeprefix("git version "), "-", git_answer.code == 0)

    if git is None or git_answer.code is None:
        findings.append("git: not runnable, and every part of this repository's process is around it")
    elif git_answer.code != 0:
        findings.append(f"git: `git --version` exited {git_answer.code} - {git_version or 'no output'}")
    elif is_a_repo(root):
        # `git config --get` exits 1 for a setting that is not there, which is an answer rather than
        # a failure - so this is the one probe whose status is deliberately not read.
        hooks = capture(root, "git", "config", "--get", "core.hooksPath").output.strip()
        if hooks != ".githooks":
            NOTES.append(
                f"tools: core.hooksPath is `{hooks or 'unset'}`, so .githooks/pre-commit did not run on "
                "this commit - enable it with: git config core.hooksPath .githooks"
            )

    # 5. The tools themselves, as the manifest records them. Without a vendor/ there is nothing to
    #    run them from, which is a state a fresh clone is in rather than a defect: it is reported so
    #    a green run cannot be mistaken for "the tools were checked".
    entries = manifest_tools(root)

    if not entries:
        if php is None:
            NOTES.append("tools: there is no PHP here, so bin/tool-paths.php could not be asked what its tools are")
        else:
            findings.append("bin/tool-paths.php: no tool entries could be read - the manifest is what runs a tool")
    elif not (root / "vendor").is_dir():
        NOTES.append(
            "tools: no vendor/ beside this checkout, so the tools were not run - "
            "composer install puts them there"
        )
        for name, entry in sorted(entries.items()):
            health(name, "", str(entry.get("pin", "")), False)
    else:
        for name, entry in sorted(entries.items()):
            path = entry["path"]

            if not (root / path).is_file():
                findings.append(
                    f"bin/tool-paths.php: `{name}` names {path}, which is not on disk - a caller that "
                    "reached for it would fail rather than report a skip"
                )
                continue

            # Run through the same door the composer scripts use, so what is checked is the process
            # as well as the tool: bin/tool.php resolves the path from the manifest and runs it under
            # PHP_BINARY, which is the interpreter that installed the dependencies.
            answer = capture(root, *tool_command(root, name, "--version"), timeout=120)
            first = (answer.output.strip().splitlines() or [""])[0]

            # The row follows the status, not the output: a tool that printed something and exited
            # non-zero has not answered the question, and the table is read to see which part of the
            # machine moved - a `ran: yes` beside a crash is the reading this batch is about.
            health(name, first, str(entry.get("pin", "")), answer.code == 0)

            if answer.code is None:
                findings.append(f"{name}: `bin/tool.php {name} --version` could not be run")
            elif answer.code != 0:
                findings.append(
                    f"{name}: `bin/tool.php {name} --version` exited {answer.code} - "
                    f"{first or 'no output'}"
                )
            elif not first:
                findings.append(f"{name}: answered `bin/tool.php {name} --version` with nothing - it did not start")

    for program in ("checks.php", "commit.php", "coverage.php", "release.php", "tool.php", "tool-paths.php"):
        if not (root / "bin" / program).is_file():
            findings.append(f"bin/{program}: missing, and this repository's process is built on it")

    # 6. The one place that decides which PHP runs, asked to prove its own ladder. The `interpreter`
    #    step above reads the four callers; this is the other half of the same question, because a
    #    rung that stopped answering would show up as a machine that cannot commit and a build that
    #    installs nothing. It is a shell script, so a machine with no `sh` is a note rather than a
    #    finding: the hook needs one to run at all, and a Windows machine without Git installed is a
    #    machine where this package's process was never available.
    resolver = root / ".agents" / "php-bin.sh"
    shell = shutil.which("sh")

    if not resolver.is_file():
        findings.append(".agents/php-bin.sh: missing, and it is where the interpreter is decided")
    elif shell is None:
        NOTES.append("tools: no `sh` on PATH, so .agents/php-bin.sh was not asked to prove its ladder")
    else:
        findings += run_process(root, shell, str(resolver), "--selftest")

    return findings


