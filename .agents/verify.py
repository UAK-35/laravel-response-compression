def command_names(text: str) -> list[str]:
    """The commands a description names: a bare or backticked token of the command shape."""
    found: list[str] = []

    for chunk in re.split(r"[\s,.;:()]+", text):
        token = chunk.strip("`\"'")
        if COMMAND_NAME.match(token):
            found.append(token)

    return found


